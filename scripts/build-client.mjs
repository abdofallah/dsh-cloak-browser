// Inline settings.js into client.js between the BEGIN/END markers.
// The Client module loader runs one self-contained script, so shared modules are inlined.
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const settings = (await readFile(new URL("settings.js", root), "utf8"))
  .replace(/^export (const|function) /gm, "$1 ")
  .trimEnd();
const clientUrl = new URL("client.js", root);
const client = await readFile(clientUrl, "utf8");
const begin = "    // BEGIN settings.js (generated by scripts/build-client.mjs)";
const end = "    // END settings.js";
const start = client.indexOf(begin);
const stop = client.indexOf(end);
if (start < 0 || stop < start) throw new Error("settings markers not found in client.js");
const body = settings.split("\n").map((line) => (line ? `    ${line}` : line)).join("\n");
const next = `${client.slice(0, start)}${begin}\n${body}\n${client.slice(stop)}`;
if (next !== client) await writeFile(clientUrl, next);
console.log(next === client ? "client.js up to date" : "client.js updated");
